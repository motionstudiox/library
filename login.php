// Redirect if already logged in
SessionManager::redirectIfLoggedIn();

$error = '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $username = sanitizeInput($_POST['username'] ?? '');
    $password = $_POST['password'] ?? '';
    
    if (empty($username) || empty($password)) {
        $error = 'Both username and password are required.';
    } else {
        $result = $db->query("SELECT id, username, full_name, password_hash FROM users WHERE username = '" . sanitizeSQL($username) . "' LIMIT 1");
        
        if ($result && $result->num_rows === 1) {
            $user = $result->fetch_assoc();
            
            if (verifyPassword($password, $user['password_hash'])) {
                SessionManager::startSession($user['id'], $user['username'], $user['full_name']);
                header('Location: ' . SITE_URL . '/dashboard.php');
                exit;
            } else {
                $error = 'Invalid password.';
            }
        } else {
            $error = 'Username not found.';
        }
    }
}
